// Turns the official brand SVGs from theSVG (assets/brand-icons/*.svg, fetched with
// `npx @thesvg/cli add whatsapp instagram facebook --dir ./assets/brand-icons`) into React
// components. The artwork stays verbatim; only element IDs get a per-instance prefix so
// gradients never collide when an icon appears more than once on the page.
import { readFile, writeFile, mkdir } from 'node:fs/promises';

const icons = [
  { slug: 'whatsapp', name: 'WhatsappIcon', label: 'WhatsApp' },
  { slug: 'instagram', name: 'InstagramIcon', label: 'Instagram' },
  { slug: 'facebook', name: 'FacebookIcon', label: 'Facebook' },
];

await mkdir('src/components/brand-icons', { recursive: true });
for (const { slug, name, label } of icons) {
  const svg = (await readFile(`assets/brand-icons/${slug}.svg`, 'utf8')).trim();
  const root = svg.match(/^<svg([^>]*)>/)[1];
  const viewBox = root.match(/viewBox="([^"]+)"/)[1];
  const fill = root.match(/\sfill="([^"]+)"/)?.[1];
  let inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
  const ids = [...inner.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]);
  for (const id of ids) {
    inner = inner
      .replaceAll(`id="${id}"`, `id="__P__${id}"`)
      .replaceAll(`url(#${id})`, `url(#__P__${id})`)
      .replaceAll(`href="#${id}"`, `href="#__P__${id}"`);
  }
  const code = `// Generated by scripts/brand-icons.mjs from theSVG's official ${label} artwork. Do not edit.
import type { BrandIconProps } from "./types";

const INNER = ${JSON.stringify(inner)};

export function ${name}({ className, title, idPrefix = "${slug.slice(0, 2)}" }: BrandIconProps) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="${viewBox}"${fill ? `\n      fill="${fill}"` : ''}
      className={className}
      role={title ? "img" : undefined}
      aria-label={title}
      aria-hidden={title ? undefined : true}
      focusable="false"
      dangerouslySetInnerHTML={{ __html: INNER.replaceAll("__P__", \`\${idPrefix}-\`) }}
    />
  );
}
`;
  await writeFile(`src/components/brand-icons/${slug}.tsx`, code);
  console.log(`src/components/brand-icons/${slug}.tsx (${ids.length} ids prefixed)`);
}
await writeFile(
  'src/components/brand-icons/types.ts',
  `export type BrandIconProps = {\n  className?: string;\n  /** Accessible name. Omit when the icon sits next to visible text (it is then hidden from assistive tech). */\n  title?: string;\n  /** Unique per instance when the same icon appears more than once (keeps gradient IDs unique). */\n  idPrefix?: string;\n};\n`,
);
